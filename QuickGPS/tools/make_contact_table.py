"""Generates src/KnownPlaces.cs from tools/mapgenie_points.txt.

Map Genie positions are map longitude/latitude. They are converted to GTA IV world X/Y with an affine fit on
shops whose game positions are known from QuickGPS F9 dumps (the same shops are on Map Genie).
Run: python tools/make_contact_table.py   (from the QuickGPS folder)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "KnownPlaces.cs")

# (map lng, map lat) -> (game x, game y): gun shops, internet cafes, Pay 'n' Sprays from F9 dumps.
GAME = {
    "gun": [(1054, 87), (66, -342), (-1338, 308)],
    "internet": [(977, -169), (-341, 1392), (-1584, 466)],
    "pns": [(1058, -287), (-307, 1549), (-514, 376), (-1148, 1176), (-1300, 274)],
}
MAP = {
    "gun": [(-0.691346, 0.55453), (-0.938827, 0.668306), (-0.517745, 0.631071)],
    "internet": [(-0.763006, 0.860048), (-0.982085, 0.696113), (-0.531414, 0.584701)],
    "pns": [(-0.757427, 0.886138), (-0.793307, 0.681484), (-0.902676, 0.821662), (-0.931788, 0.662299), (-0.51708, 0.564789)],
}
# Held-out checks (not used in the fit): map point -> game position from F9 dumps.
CHECKS = [("Lost MC Clubhouse", (-1.004299, 0.675608), (-1713, 358)), ("Luis' Apartment", (-0.780866, 0.859991), (-445, 1390))]

MERGE_M = 40.0          # Map Genie stacks several missions of one giver a few metres apart; merge them
NAME_FIXES = {"Adriana Yanira Lopez": "Adriana Lopez"}


def lstsq3(rows, ys):
    m = [[sum(r[i] * r[j] for r in rows) for j in range(3)] for i in range(3)]
    v = [sum(r[i] * y for r, y in zip(rows, ys)) for i in range(3)]
    a = [m[i] + [v[i]] for i in range(3)]
    for i in range(3):
        p = max(range(i, 3), key=lambda r: abs(a[r][i]))
        a[i], a[p] = a[p], a[i]
        for r in range(3):
            if r != i:
                f = a[r][i] / a[i][i]
                a[r] = [x - f * y for x, y in zip(a[r], a[i])]
    return [a[i][3] / a[i][i] for i in range(3)]


def fit():
    coef = [5682, 0, 3996, 0, 5670, -3484]   # rough start; refined by matching + least squares
    pairs = []
    for _ in range(6):
        pairs = []
        for kind in GAME:
            for p in MAP[kind]:
                q = to_game(p, coef)
                pairs.append((p, min(GAME[kind], key=lambda g: math.dist(g, q))))
        rows = [(p[0], p[1], 1.0) for p, _ in pairs]
        coef = lstsq3(rows, [g[0] for _, g in pairs]) + lstsq3(rows, [g[1] for _, g in pairs])
    errors = [math.dist(to_game(p, coef), g) for p, g in pairs]
    return coef, max(errors)


def to_game(p, c):
    return (c[0] * p[0] + c[1] * p[1] + c[2], c[3] * p[0] + c[4] * p[1] + c[5])


def merge(points):
    """Merges a character's stacked markers (several missions a few metres apart) into one point per place."""
    merged = []
    for ep, name, x, y in points:
        for m in merged:
            if m[0] == ep and m[1] == name and math.dist((m[2], m[3]), (x, y)) < MERGE_M:
                m[4].append((x, y))
                break
        else:
            merged.append([ep, name, x, y, [(x, y)]])
    out = []
    for ep, name, _, _, pts in merged:
        out.append((ep, name, sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts)))
    return sorted(out)


def main():
    coef, max_err = fit()
    print("fit on %d anchors, max error %.0f m" % (sum(len(v) for v in GAME.values()), max_err))
    for name, p, g in CHECKS:
        print("check %-18s error %.0f m" % (name, math.dist(to_game(p, coef), g)))
    if max_err > 25:
        raise SystemExit("fit too loose, not writing")

    areas, givers, randoms = [], [], []
    with open(os.path.join(HERE, "mapgenie_points.txt"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            for item in line.strip().split("|"):
                tag, lng, lat, name = item.split(";")
                x, y = to_game((float(lng), float(lat)), coef)
                name = NAME_FIXES.get(name, name)
                if tag == "N":
                    areas.append((name, x, y))
                elif tag == "R":
                    randoms.append(("ANY", name, x, y))
                else:
                    givers.append(({"L": "TLAD", "T": "TBoGT", "G": "GTAIV"}[tag], name, x, y))

    places = merge(givers)
    random_places = merge(randoms)
    areas.sort()

    lines = [
        "// Generated by tools/make_contact_table.py from Map Genie data (https://mapgenie.io/grand-theft-auto-4).",
        "// Do not edit by hand: change tools/mapgenie_points.txt and re-run the script.",
        "namespace QuickGPS",
        "{",
        "    static class KnownPlaces",
        "    {",
        "        // Episode, name, game X, game Y: where each mission giver's missions start (GTAIV, TLAD, TBoGT).",
        "        public static readonly KnownPlace[] MissionGivers = new KnownPlace[] {",
    ]
    for ep, name, x, y in places:
        lines.append('            new KnownPlace("%s", "%s", %.0ff, %.0ff),' % (ep, name, x, y))
    lines += ["        };", "",
              "        // Random characters (Stranger blips). Map Genie doesn't say which episode, so they match in all.",
              "        public static readonly KnownPlace[] RandomCharacters = new KnownPlace[] {"]
    for ep, name, x, y in random_places:
        lines.append('            new KnownPlace("%s", "%s", %.0ff, %.0ff),' % (ep, name, x, y))
    lines += ["        };", "", "        // Neighbourhood label positions, for naming the area a contact is in.",
              "        public static readonly KnownPlace[] Areas = new KnownPlace[] {"]
    for name, x, y in areas:
        lines.append('            new KnownPlace(null, "%s", %.0ff, %.0ff),' % (name, x, y))
    lines += ["        };", "    }", "", "    class KnownPlace", "    {",
              "        public readonly string Episode, Name;", "        public readonly float X, Y;",
              "        public KnownPlace(string episode, string name, float x, float y)",
              "        {", "            Episode = episode; Name = name; X = x; Y = y;", "        }", "    }", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %d mission-giver places, %d random-character places and %d areas to %s"
          % (len(places), len(random_places), len(areas), os.path.relpath(OUT)))


if __name__ == "__main__":
    main()
